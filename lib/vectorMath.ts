// 1 = identical direction, 0 = unrelated, negative = opposed. Embeddings
// from this app's model are normalized (unit length), so the dot product
// alone would already equal cosine similarity — dividing by the norms
// anyway keeps this correct even if a caller passes in a non-normalized
// vector.
export function cosineSimilarity(a: number[], b: number[]): number {
  if (a.length === 0 || b.length === 0 || a.length !== b.length) return 0;

  let dot = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }
  if (normA === 0 || normB === 0) return 0;

  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
